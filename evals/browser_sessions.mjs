/** Real owner conversation lifecycle; only this test's newly-created session is deleted. */
import {createRequire} from 'node:module';
import {readFileSync,writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const [packagePath,tokenFile,output]=process.argv.slice(2);
const token=readFileSync(tokenFile,'utf8').trim();
const {chromium}=createRequire(import.meta.url)(packagePath);
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const base=process.env.SANCTUM_BASE_URL??'http://127.0.0.1:8769';
const foreign=[];const errors=[];let session;
page.on('request',r=>{if(new URL(r.url()).origin!==new URL(base).origin)foreign.push(r.url());});
page.on('pageerror',e=>errors.push(e.message));
page.on('request',r=>{if(r.url().endsWith('/v1/chat/completions'))session=r.headers()['x-sanctum-conversation'];});
try {
 await page.goto(base);
 const headers={Authorization:`Bearer ${token}`};
 assert.equal((await page.request.post(`${base}/v1/sessions`,{data:{operation:'list',query:'',offset:0}})).status(),401);
 assert.equal((await page.request.post(`${base}/v1/sessions`,{headers,data:{operation:'delete',id:'missing',owner:'other'}})).status(),400);
 assert.equal((await page.request.post(`${base}/v1/sessions`,{headers,data:{operation:'delete',id:'missing'}})).status(),404);
 assert.equal((await page.request.post(`${base}/v1/sessions`,{headers,data:'x'.repeat(4097)})).status(),413);
 await page.getByLabel('Local access key').fill(token);
 await page.getByRole('button',{name:'Unlock',exact:true}).click();
 await page.getByLabel('Model',{exact:true}).waitFor();
 await page.getByLabel('Message',{exact:true}).fill('Reply with hello.');
 await page.getByRole('button',{name:'Send ↑',exact:true}).click();
 await page.getByRole('button',{name:'Stop generation',exact:true}).waitFor({state:'hidden'});
 assert(session,'chat must provide its new session ID');
 const original=`Conversation ${session.slice(0,8)}`;
 await page.getByLabel(`Actions for ${original}`,{exact:true}).click();
 await page.getByRole('button',{name:`Rename ${original}`,exact:true}).click();
 const title=`Audit ${session.slice(0,8)} <img src=x>`;
 await page.getByLabel('Conversation title').fill(title);
 await page.getByRole('button',{name:'Save title',exact:true}).click();
 await page.getByRole('button',{name:title,exact:true}).waitFor();
 await page.getByLabel('Search conversations').fill(`Audit ${session.slice(0,8)}`);
 await page.getByRole('button',{name:'Search',exact:true}).click();
 const nav=page.getByRole('navigation',{name:'Saved conversations'});
 await page.waitForFunction(()=>document.querySelector('nav[aria-label="Saved conversations"]')?.querySelectorAll('div.my-2').length===1);
 assert.equal(await nav.locator('img').count(),0,'title must remain inert text');
 await page.screenshot({path:output.replace(/\.json$/,'-history.png')});
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Open navigation',exact:true}).click();
 await page.getByLabel(`Actions for ${title}`,{exact:true}).click();
 await page.getByRole('button',{name:`Rename ${title}`,exact:true}).click();
 await page.keyboard.press('Escape');
 await page.getByRole('dialog',{name:'Rename conversation',exact:true}).waitFor({state:'hidden'});
 assert.equal(await page.getByRole('dialog',{name:'Navigation',exact:true}).count(),1,'Escape only closes the nested rename dialog');
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:output.replace(/\.json$/,'-mobile.png')});
 await page.setViewportSize({width:1440,height:900});
 await page.getByRole('button',{name:'＋ New conversation',exact:true}).click();
 await page.getByRole('button',{name:title,exact:true}).click();
 await page.locator('article').first().waitFor();
 assert((await page.locator('article').last().textContent()).length>8);
 await page.getByLabel(`Actions for ${title}`,{exact:true}).click();
 await page.getByRole('button',{name:`Delete ${title}`,exact:true}).click();
 await page.getByRole('button',{name:'Close Delete conversation',exact:true}).click();
 assert.equal(await page.getByRole('button',{name:title,exact:true}).count(),1,'dismiss must preserve conversation');
 await page.getByLabel(`Actions for ${title}`,{exact:true}).click();
 await page.getByRole('button',{name:`Delete ${title}`,exact:true}).click();
 await page.getByRole('button',{name:'Confirm delete',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('dialog[open]')===null);
 await page.getByText('No saved conversations found.',{exact:true}).waitFor();
 assert.equal(await page.getByRole('button',{name:'Undo',exact:true}).count(),0,'hard deletion has no restore endpoint;do not offer a pretend Undo');
 const stored=await (await page.request.get(`${base}/v1/conversations/${session}`,{headers})).json();
 assert.deepEqual(stored.data,[]);
 assert.equal(await page.locator('article').count(),0);
 assert.deepEqual(foreign,[]);assert.deepEqual(errors,[]);
 await page.screenshot({path:output.replace(/\.json$/,'.png')});
 const result={suite:'real-conversation-history',passed:['owner_auth','unknown_fields_rejected','missing_404','body_limit','real_chat_saved','rename','search','restore','dismiss_delete','confirm_delete','legacy_turns_deleted','inert_title','same_origin','mobile_escape','mobile_no_overflow'],foreign_requests:foreign,page_errors:errors};
 writeFileSync(output,JSON.stringify(result,null,2)+'\n');console.log(JSON.stringify(result,null,2));
}finally{await browser.close();}
